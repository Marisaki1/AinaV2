// Isolated data, headless browser; no Discord or existing account writes.
const { chromium } = require('playwright');
const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), net = require('node:net'), assert = require('node:assert/strict');
const { createService } = require('../src/critter/server');
async function port() { const server = net.createServer(); await new Promise(r => server.listen(0, '127.0.0.1', r)); const value = server.address().port; await new Promise(r => server.close(r)); return value; }
(async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'aina-manuscripts-'));
  const service = createService({ directory: path.join(directory, 'aina'), port: 0, worldbuilderOptions: { enabled: true, data: path.join(directory, 'wb-data'), port: await port() } });
  let browser;
  try {
    await service.start();
    browser = await chromium.launch({ executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true });
    const context = await browser.newContext({ viewport: { width: 1500, height: 1100 }, acceptDownloads: true });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', e => errors.push(e.message)); page.on('dialog', d => d.accept());
    await page.goto(service.worldbuilder.url + '/#/home');
    await page.getByRole('button', { name: 'Switch to create account', exact: true }).click();
    await page.getByLabel('Username', { exact: true }).fill('writing_test');
    await page.getByLabel('Display name', { exact: true }).fill('Test writer');
    await page.getByLabel('Your first world', { exact: true }).fill('Writing test world');
    await page.getByLabel('Password', { exact: true }).fill('isolated-writing-test');
    await page.getByLabel('Confirm password', { exact: true }).fill('isolated-writing-test');
    await page.getByRole('button', { name: 'Create account', exact: true }).click();
    await page.getByLabel('Account menu', { exact: true }).waitFor();
    const fixture = await page.evaluate(async () => {
      const boot = await (await fetch('/api/bootstrap')).json(), world = boot.worlds[0].id;
      const cookie = document.cookie.split('; ').find(v => v.startsWith(boot.csrf_cookie + '='));
      const send = async value => {
        const response = await fetch('/api/worlds/' + world + '/resources', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-CSRFToken': decodeURIComponent(cookie.split('=').slice(1).join('=')) }, body: JSON.stringify(value) });
        const entry = await response.json(); if (!response.ok) throw Error(JSON.stringify(entry)); return entry;
      };
      const doc = text => ({ type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text }] }] });
      const book = await send({ title: 'Book browser fixture', kind: 'manuscript', data: { unknown: 'Preserve original' } });
      const chapter = await send({ title: 'Chapter one', kind: 'chapter', parent: book.id });
      const first = await send({ title: 'Scene A', kind: 'scene', parent: chapter.id, position: 0, document: doc('Alpha words before revision') });
      const second = await send({ title: 'Scene B', kind: 'scene', parent: chapter.id, position: 1, document: doc('Beta scene remains original') });
      const lore = await send({ title: 'Reference lore', kind: 'article', document: doc('Lighthouse research reference'), private_notes: 'Private lore secret' });
      return { book: book.id, chapter: chapter.id, first: first.id, second: second.id, lore: lore.id };
    });
    const get = async suffix => page.evaluate(async suffix => (await (await fetch('/api' + suffix)).json()), suffix);
    const compilePath = `/resources/${fixture.book}/manuscript/compile`;
    await page.evaluate(id => location.hash = '/writing/' + id, fixture.book);
    await page.getByLabel('Entry title', { exact: true }).waitFor();
    await page.getByLabel('Entry content', { exact: true }).fill('Unsaved alpha revision');
    await page.getByRole('button', { name: 'Research & references', exact: true }).click();
    await page.getByLabel('Search manuscript research', { exact: true }).fill('Lighthouse');
    await page.locator('.manuscript-research-results').getByRole('button', { name: 'Reference lore', exact: true }).click();
    await page.locator('.manuscript-research article').getByText('Lighthouse research reference', { exact: true }).waitFor();
    assert.equal(await page.getByLabel('Entry content', { exact: true }).textContent(), 'Unsaved alpha revision');
    await page.getByLabel('Pin research Reference lore', { exact: true }).click();
    await page.waitForFunction(async id => (await (await fetch('/api/resources/' + id)).json()).data.writing_research?.length === 1, fixture.book);
    await page.getByRole('button', { name: 'Close research', exact: true }).click();
    await page.getByLabel('Filter manuscript outline', { exact: true }).fill('Unsaved alpha revision');
    await page.waitForFunction(() => document.querySelectorAll('.manuscript-outline-row').length === 1);
    assert.ok((await page.locator('.manuscript-outline').textContent()).includes('Scene A'));
    await page.getByLabel('Filter manuscript outline', { exact: true }).fill('');
    await page.getByRole('button', { name: 'Draft checkpoints', exact: true }).click();
    await page.getByLabel('Checkpoint name', { exact: true }).fill('Before structural edit');
    await page.getByRole('button', { name: 'Create checkpoint', exact: true }).click();
    await page.getByRole('button', { name: 'Review checkpoint Before structural edit', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Corkboard', exact: true }).click();
    await page.getByLabel('Corkboard move Scene B earlier', { exact: true }).click();
    await page.waitForFunction(async path => (await (await fetch('/api' + path)).json()).nodes[1].title === 'Scene B', compilePath);
    await page.getByLabel('New manuscript node title', { exact: true }).fill('Chapter two');
    await page.getByRole('button', { name: 'Add chapter', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[aria-label="Entry title"]')?.value === 'Chapter two');
    const extra = (await get(`/resources/${fixture.book}/manuscript`)).nodes.find(e => e.title === 'Chapter two').id;
    await page.locator('.manuscript-outline-row').filter({ hasText: 'Scene A' }).locator('button').first().click();
    await page.waitForFunction(() => document.querySelector('[aria-label="Entry title"]')?.value === 'Scene A');
    await page.locator('.writing-tree details summary').click();
    await page.getByRole('combobox', { name: 'Move node into', exact: true }).click();
    await page.getByRole('option', { name: 'Chapter two', exact: true }).click();
    await page.locator('.writing-tree details').getByRole('button', { name: 'Move selected node', exact: true }).click();
    await page.waitForFunction(async ({ first, extra }) => (await (await fetch('/api/resources/' + first)).json()).parent === extra, { first: fixture.first, extra });
    await page.getByRole('button', { name: 'Book settings', exact: true }).click();
    const settings = page.getByRole('dialog', { name: 'Manuscript settings', exact: true });
    await settings.getByLabel('Manuscript word goal', { exact: true }).fill('5000');
    await settings.getByLabel('Author', { exact: true }).fill('Test author');
    await settings.getByRole('button', { name: 'Save manuscript settings', exact: true }).click();
    await settings.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'Review', exact: true }).click();
    await page.getByLabel('Include Scene B in compilation', { exact: true }).click();
    await page.waitForFunction(async path => !(await (await fetch('/api' + path)).json()).nodes.some(e => e.title === 'Scene B'), compilePath);
    await page.getByRole('button', { name: 'Publish selected snapshots', exact: true }).click();
    await page.waitForFunction(async path => (await (await fetch('/api' + path + '?audience=reader')).json()).reader === true, compilePath);
    await page.getByRole('button', { name: 'Read', exact: true }).click();
    await page.locator('.manuscript-reading').getByText('Unsaved alpha revision', { exact: true }).waitFor();
    assert.equal(await page.locator('.manuscript-reading').getByText('Beta scene remains original', { exact: true }).count(), 0);
    const pendingDownload = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download book HTML', exact: true }).click();
    const download = await pendingDownload, filename = path.join(directory, 'compiled-book.html'); await download.saveAs(filename);
    const offline = await context.newPage();
    await offline.route(/^https?:/, route => route.abort('blockedbyclient'));
    await offline.goto('file:///' + filename.replaceAll('\\', '/'));
    await offline.getByRole('heading', { name: 'Book browser fixture', exact: true }).waitFor();
    assert.ok((await offline.locator('body').textContent()).includes('Unsaved alpha revision'));
    await offline.getByRole('link', { name: 'Scene A', exact: true }).click();
    assert.equal(await offline.evaluate(() => location.hash), '#node-' + fixture.first);
    await offline.close();
    await page.getByRole('combobox', { name: 'Edition', exact: true }).click();
    await page.getByRole('option', { name: 'Published reader snapshots', exact: true }).click();
    await page.locator('.manuscript-reading').getByText('Unsaved alpha revision', { exact: true }).waitFor();
    const reader = await get(compilePath + '?audience=reader');
    assert.equal(reader.book.data.writing_checkpoints, undefined); assert.equal(reader.book.data.writing_research, undefined);
    await page.getByRole('button', { name: 'Draft checkpoints', exact: true }).click();
    await page.getByRole('button', { name: 'Review checkpoint Before structural edit', exact: true }).click();
    const preview = page.getByRole('dialog', { name: 'Review draft: Before structural edit', exact: true });
    await preview.getByRole('heading', { name: 'Newer writing retained outside this draft', exact: true }).waitFor();
    await page.route('**/manuscript/checkpoints/*', route => route.request().method() === 'POST' ? route.abort('failed') : route.continue());
    await preview.getByRole('button', { name: 'Restore reviewed checkpoint', exact: true }).click();
    await preview.getByRole('alert').waitFor(); assert.equal(await preview.isVisible(), true);
    await page.unroute('**/manuscript/checkpoints/*');
    await preview.getByRole('button', { name: 'Restore reviewed checkpoint', exact: true }).click();
    await preview.waitFor({ state: 'hidden' });
    assert.equal((await get('/resources/' + fixture.first)).parent, fixture.chapter);
    assert.equal((await get('/resources/' + extra)).parent, null);
    assert.equal((await get('/resources/' + fixture.book)).data.unknown, 'Preserve original');
    await page.getByRole('button', { name: 'Read', exact: true }).click();
    for (const width of [390, 1024, 1500]) {
      await page.setViewportSize({ width, height: 1100 });
      assert.ok(await page.locator('.manuscript-layout').evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'Manuscript overflow at ' + width);
    }
    await page.screenshot({ path: path.join(directory, 'writing-workspace.png') });
    assert.deepEqual(errors, []);
    console.log('PASS nested outline, corkboard order, scene moves, full-text search, research without losing edits, checkpoints/recovery, selected publication, offline HTML and 390/1024/1500 layouts.');
    console.log('Manuscript artifacts: ' + directory);
  } finally { if (browser) await browser.close(); await service.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
